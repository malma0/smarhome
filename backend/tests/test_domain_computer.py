def test_find_installed_app_prefers_exact_match_over_substring(monkeypatch):
    apps = [
        {"Name": "Steam", "AppID": "exact-id"},
        {"Name": "Steam Support Center", "AppID": "substring-id"},
    ]
    monkeypatch.setattr("app.domains.computer._list_start_apps", lambda: apps)

    match = _find_installed_app("Steam")

    assert match["AppID"] == "exact-id"


