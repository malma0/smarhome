"""No real program ever launches in these tests - subprocess.Popen and
os.startfile are mocked throughout, and _list_start_apps (which would shell
out to PowerShell for real) is always mocked with canned data."""

import asyncio
from unittest.mock import patch

from app.domains.computer import KNOWN_APPS, _find_installed_app, register
from app.tools.registry import ToolRegistry, TurnContext

_FAKE_START_APPS = [
    {"Name": "Steam", "AppID": r"{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\Steam\Steam.exe"},
    {"Name": "Blender", "AppID": "steam://rungameid/365670"},
    {"Name": "Developer PowerShell for VS 2022", "AppID": "Microsoft.AutoGenerated.{some-guid}"},
    {"Name": "Git Bash", "AppID": "Microsoft.AutoGenerated.{other-guid}"},
]


def make_registry() -> ToolRegistry:
    registry = ToolRegistry()
    register(registry)
    return registry


def test_registers_exactly_one_tool():
    registry = make_registry()
    names = [t.name for t in registry.definitions()]
    assert names == ["open_application"]


def test_opens_known_app_by_exact_name():
    registry = make_registry()
    ctx = TurnContext()
    with patch("app.domains.computer.subprocess.Popen") as mock_popen:
        result = asyncio.run(registry.dispatch("open_application", {"app": "notepad"}, ctx))

    mock_popen.assert_called_once_with(["notepad.exe"])
    assert result == {"ok": True, "opened": "notepad"}
    assert "notepad" in ctx.touched


