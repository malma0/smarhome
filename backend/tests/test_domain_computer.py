def test_generic_app_found_by_exact_name_launches_via_apps_folder():
    registry = make_registry()
    ctx = TurnContext()
    with (
        patch("app.domains.computer._list_start_apps", return_value=_FAKE_START_APPS),
        patch("app.domains.computer.subprocess.Popen") as mock_popen,
    ):
        result = asyncio.run(registry.dispatch("open_application", {"app": "Steam"}, ctx))

    mock_popen.assert_called_once_with(
        ["explorer.exe", r"shell:AppsFolder\{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\Steam\Steam.exe"]
    )
    assert result == {"ok": True, "opened": "Steam"}
    assert "Steam" in ctx.touched


